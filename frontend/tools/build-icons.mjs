// Builds the Obsidian Bloom icon sprite from the ASCII grids in src/assets/icons/*.txt, and checks it is up to date.
//
// Usage: node tools/build-icons.mjs build | check.
//   build  writes src/assets/icons/sprite.svg and src/app/shared/ui/icon-names.ts from the grids.
//   check  writes nothing; exit status 1 when a grid is invalid or a built file differs from what the grids give.
// The output depends on the grids only (sorted names, no timestamp), so building twice gives identical files.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

/** Folder of the grids, relative to the frontend folder. */
export const GRID_DIR = 'src/assets/icons';
/** The SVG sprite: one <symbol> per grid, referenced as sprite.svg#name. */
export const SPRITE_FILE = 'src/assets/icons/sprite.svg';
/** The TypeScript list of icon names and sizes, so a template cannot name an icon that does not exist. */
export const NAMES_FILE = 'src/app/shared/ui/icon-names.ts';

/** The icons docs/design-system.md requires, all on a 16 x 16 grid. */
export const REQUIRED_ICONS = [
  'chat', 'plus', 'search', 'pin', 'archive', 'trash', 'pencil', 'refresh', 'image', 'send',
  'check', 'check-double', 'arrow-left', 'arrow-right', 'chevron', 'close', 'gear', 'user', 'brain', 'lock',
  'unlock', 'bell', 'star', 'upload', 'download', 'warning', 'error', 'gpu', 'scene', 'clock',
];

const EMPTY_STATE_PREFIX = 'empty-';
const NAME = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/;

/**
 * Parses one grid: "#" is a filled pixel, "." an empty one. The grid is square and 16 x 16, or 24 x 24 when the name
 * starts with "empty-" (the empty-state icons). Throws an Error naming the icon and the problem otherwise.
 * Returns { name, size, rows }.
 */
export function parseGrid(name, text) {
  if (!NAME.test(name)) {
    throw new Error(`${name}: icon names are lowercase words joined by hyphens`);
  }
  const rows = text.replace(/\r\n/g, '\n').replace(/\n+$/, '').split('\n');
  const size = name.startsWith(EMPTY_STATE_PREFIX) ? 24 : 16;
  if (rows.length !== size) {
    throw new Error(`${name}: expected ${size} rows, found ${rows.length}`);
  }
  rows.forEach((row, index) => {
    if (row.length !== size) {
      throw new Error(`${name}: row ${index + 1} has ${row.length} columns, expected ${size}`);
    }
    if (/[^#.]/.test(row)) {
      throw new Error(`${name}: row ${index + 1} holds a character other than "#" and "."`);
    }
  });
  if (!rows.some((row) => row.includes('#'))) {
    throw new Error(`${name}: the grid is empty`);
  }
  return { name, size, rows };
}

/** SVG path data of a grid: one rectangle per horizontal run of filled pixels, in reading order. */
export function gridPath(rows) {
  const rectangles = [];
  rows.forEach((row, y) => {
    for (const run of row.matchAll(/#+/g)) {
      rectangles.push(`M${run.index} ${y}h${run[0].length}v1h-${run[0].length}z`);
    }
  });
  return rectangles.join('');
}

/** The sprite text for grids already sorted by name. */
export function buildSprite(grids) {
  const symbols = grids.map(
    ({ name, size, rows }) =>
      `  <symbol id="${name}" viewBox="0 0 ${size} ${size}">` +
      `<path d="${gridPath(rows)}" fill="currentColor" shape-rendering="crispEdges"/></symbol>`,
  );
  return ['<svg xmlns="http://www.w3.org/2000/svg">', ...symbols, '</svg>', ''].join('\n');
}

/** The TypeScript module text listing every icon name with its size. */
export function buildNames(grids) {
  const entries = grids.map(({ name, size }) => `  '${name}': ${size},`);
  return [
    '// Generated by tools/build-icons.mjs from src/assets/icons/*.txt. Do not edit by hand: run "node tools/build-icons.mjs build".',
    '',
    '/** Every icon of the sprite with the side of its grid in pixels. */',
    'export const ICON_SIZES = {',
    ...entries,
    '} as const;',
    '',
    '/** The name of an icon of the sprite. */',
    'export type IconName = keyof typeof ICON_SIZES;',
    '',
  ].join('\n');
}

/** Reads and validates every grid under root, sorted by name. Throws when a grid is invalid or a required one is missing. */
export function readGrids(root) {
  const directory = join(root, GRID_DIR);
  const names = readdirSync(directory)
    .filter((file) => file.endsWith('.txt'))
    .map((file) => file.slice(0, -'.txt'.length))
    .sort();
  const grids = names.map((name) => parseGrid(name, readFileSync(join(directory, `${name}.txt`), 'utf8')));
  const missing = REQUIRED_ICONS.filter((name) => !names.includes(name));
  if (missing.length > 0) {
    throw new Error(`missing required icons: ${missing.join(', ')}`);
  }
  return grids;
}

/** Returns the built files as { path relative to root: text }. */
export function buildIcons(root) {
  const grids = readGrids(root);
  return { [SPRITE_FILE]: buildSprite(grids), [NAMES_FILE]: buildNames(grids) };
}

function readNormalized(path) {
  try {
    return readFileSync(path, 'utf8').replace(/\r\n/g, '\n');
  } catch {
    return null;
  }
}

/** Returns one message per problem: an invalid grid, or a built file that is missing or differs from the grids. */
export function checkIcons(root) {
  let built;
  try {
    built = buildIcons(root);
  } catch (error) {
    return [error.message];
  }
  return Object.entries(built)
    .filter(([file, text]) => readNormalized(join(root, file)) !== text)
    .map(([file, text]) => {
      const line = firstDifferingLine(readNormalized(join(root, file)), text);
      return `${file} is out of date with ${GRID_DIR}/*.txt (first difference at line ${line}); run "node tools/build-icons.mjs build"`;
    });
}

/** 1-based number of the first line where two texts differ, or 1 when the first text is missing. */
export function firstDifferingLine(actual, expected) {
  if (actual === null) {
    return 1;
  }
  const have = actual.split('\n');
  const want = expected.split('\n');
  const length = Math.max(have.length, want.length);
  for (let index = 0; index < length; index += 1) {
    if (have[index] !== want[index]) {
      return index + 1;
    }
  }
  return 1;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const root = fileURLToPath(new URL('..', import.meta.url));
  const mode = process.argv[2];
  if (mode === 'build') {
    for (const [file, text] of Object.entries(buildIcons(root))) {
      mkdirSync(dirname(join(root, file)), { recursive: true });
      writeFileSync(join(root, file), text);
      console.log(`Wrote ${file}`);
    }
  } else if (mode === 'check') {
    const problems = checkIcons(root);
    for (const problem of problems) {
      console.error(problem);
    }
    console.log(`Icons: ${problems.length} problem(s)`);
    process.exitCode = problems.length === 0 ? 0 : 1;
  } else {
    console.error('Usage: node tools/build-icons.mjs build | check');
    process.exitCode = 2;
  }
}
