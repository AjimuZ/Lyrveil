"""Conversation routes of docs/api.md (Conversations): create, list, read, change, delete and restore.

Not in the committed OpenAPI document yet: `backend/openapi.json` is regenerated by the Docker `openapi` target
(see tests/unit/test_openapi_document.py), and the routes join it with the first regeneration, together with the
frontend types. Until then `include_in_schema` is off, so the document test keeps comparing what is committed.
"""

from fastapi import APIRouter, Depends, Query, Request, Response
from pydantic import BaseModel, ConfigDict, Field
from sqlalchemy import Engine

from lyrveil.domain.conversations import Activity, Conversation, ConversationStatus
from lyrveil.services.conversations import ConversationService

router = APIRouter(prefix="/conversations", tags=["conversations"], include_in_schema=False)


class LastMessageOut(BaseModel):
    """The preview of a chat's newest finished message: who wrote it, its kind and its text cut to 140 characters."""

    author: str
    kind: str
    text: str


class ConversationOut(BaseModel):
    """A conversation as the chat list and the chat header show it.

    `avatar_url` is the thumbnail route of the character's primary avatar, null while it has none. `unread_count` counts
    the finished character messages after the read mark. `last_message` is null until a message has finished.
    `activity` is `typing`, `drawing` or `queued` while the character has a reply in that state, else null.
    """

    id: str
    character_id: str
    character_name: str
    title: str
    language: str | None
    effective_language: str
    status: ConversationStatus
    pinned: bool
    pinned_at: str | None
    shares_memory: bool
    unread_count: int
    last_message_at: str | None
    created_at: str
    updated_at: str
    avatar_url: str | None = None
    scenario_id: str | None = None
    scenario_title: str | None = None
    last_message: LastMessageOut | None = None
    activity: Activity | None = None


class ConversationList(BaseModel):
    items: list[ConversationOut]


class CreateConversation(BaseModel):
    model_config = ConfigDict(extra="forbid")

    character_id: str = Field(min_length=1)
    scenario_id: str | None = None
    title: str | None = Field(default=None, max_length=200)
    language: str | None = Field(default=None, min_length=2, max_length=16)
    shares_memory: bool = False


class ReadMark(BaseModel):
    model_config = ConfigDict(extra="forbid")

    up_to_seq: int = Field(ge=0)


class PatchConversation(BaseModel):
    """Only the fields present in the body change; `title` null or blank restores the character's name and `language`
    null inherits the character's."""

    model_config = ConfigDict(extra="forbid")

    title: str | None = Field(default=None, max_length=200)
    pinned: bool = False
    archived: bool = False
    language: str | None = Field(default=None, min_length=2, max_length=16)
    shares_memory: bool = False


def _out(conversation: Conversation) -> ConversationOut:
    return ConversationOut(
        id=conversation.id,
        character_id=conversation.character_id,
        character_name=conversation.character_name,
        title=conversation.title,
        language=conversation.language,
        effective_language=conversation.effective_language,
        status=conversation.status,
        pinned=conversation.pinned,
        pinned_at=conversation.pinned_at,
        shares_memory=conversation.shares_memory,
        unread_count=conversation.unread_count,
        last_message_at=conversation.last_message_at,
        created_at=conversation.created_at,
        updated_at=conversation.updated_at,
        avatar_url=(
            None if conversation.avatar_asset_id is None else f"/media/assets/{conversation.avatar_asset_id}/thumbnail"
        ),
        scenario_id=conversation.scenario_id,
        scenario_title=conversation.scenario_title,
        last_message=(
            None
            if conversation.last_message is None
            else LastMessageOut(
                author=conversation.last_message.author,
                kind=conversation.last_message.kind,
                text=conversation.last_message.text,
            )
        ),
        activity=conversation.activity,
    )


def get_service(request: Request) -> ConversationService:
    """Returns the service on the application's engine; startup always opens one before it serves routes."""
    engine: Engine | None = request.app.state.engine
    if engine is None:
        raise RuntimeError("the conversation routes need a database")
    return ConversationService(engine)


Service = Depends(get_service)


@router.get("", response_model=ConversationList)
def list_conversations(
    status: ConversationStatus = ConversationStatus.ACTIVE,
    character_id: str | None = Query(default=None),
    q: str | None = Query(default=None, max_length=200),
    service: ConversationService = Service,
) -> ConversationList:
    """Lists the conversations in `status` (default active), pinned first and then by latest activity. Deleted ones
    are listed only with `status=deleted`, for the restore screen. `q` keeps the chats whose title or messages contain
    every word of it; it is plain text, never search syntax."""
    return ConversationList(items=[_out(item) for item in service.list_conversations(status, character_id, q)])


@router.post("", response_model=ConversationOut, status_code=201)
def create_conversation(body: CreateConversation, service: ConversationService = Service) -> ConversationOut:
    """Starts a conversation with a character, optionally from a scenario: 404 when the character or the scenario does
    not exist, 409 when the character or the scenario is archived or the scenario is for another character."""
    return _out(
        service.create(
            body.character_id,
            scenario_id=body.scenario_id,
            title=body.title,
            language=body.language,
            shares_memory=body.shares_memory,
        )
    )


@router.get("/{conversation_id}", response_model=ConversationOut)
def get_conversation(conversation_id: str, service: ConversationService = Service) -> ConversationOut:
    """Returns one conversation; 404 when it does not exist or is deleted."""
    return _out(service.get(conversation_id))


@router.patch("/{conversation_id}", response_model=ConversationOut)
def patch_conversation(
    conversation_id: str, body: PatchConversation, service: ConversationService = Service
) -> ConversationOut:
    """Changes the title, the pin, the archive state, the language or the shared-memory flag; 404 when the
    conversation does not exist or is deleted."""
    return _out(service.update(conversation_id, body.model_dump(exclude_unset=True)))


@router.post("/{conversation_id}/read", response_model=ConversationOut)
def read_conversation(conversation_id: str, body: ReadMark, service: ConversationService = Service) -> ConversationOut:
    """Marks the chat read up to message number `up_to_seq` and returns it with its new unread count. The mark only
    moves forward and never passes the last message; 404 when the conversation does not exist or is deleted."""
    return _out(service.mark_read(conversation_id, body.up_to_seq))


@router.delete("/{conversation_id}", status_code=204)
def delete_conversation(conversation_id: str, service: ConversationService = Service) -> Response:
    """Soft-deletes a conversation; 404 when it does not exist or is already deleted."""
    service.delete(conversation_id)
    return Response(status_code=204)


@router.post("/{conversation_id}/undelete", response_model=ConversationOut)
def undelete_conversation(conversation_id: str, service: ConversationService = Service) -> ConversationOut:
    """Restores a deleted conversation within 30 days: 404 when it does not exist, 409 when it is not deleted or the
    time has passed."""
    return _out(service.restore(conversation_id))
